# Declared on every authenticated router. ``auto_error=False`` because this
# only documents the scheme — ``get_current_user`` is what verifies the token,
# and it keeps answering 401 itself. Hey API reads the resulting ``security``
# entry to decide which calls get the ``Authorization`` header.
bearer_scheme = HTTPBearer(
    auto_error=False,
    scheme_name="ClerkSession",
    description="A Clerk session token.",
)


class ErrorResponse(Schema):
    """Every refusal that is not a validation failure: ``HTTPException`` and
    ``DomainError`` both answer in this shape."""

    detail: str


def error_responses(*status_codes: int) -> dict[int | str, dict[str, Any]]:
    """``responses=`` entries for refusals a route (or router) can answer."""
    descriptions = {
        400: "The request was refused.",
        401: "No valid session.",
        403: "The caller lacks the required permission.",
        404: "Not found.",
        409: "The current state refuses the request.",
        413: "The upload is too large.",
        422: "The request body failed validation.",
        502: "Object storage failed.",
        503: "A service the request depends on is unavailable.",
    }
    return {
        code: {"model": ErrorResponse, "description": descriptions[code]}
        for code in status_codes
    }


def operation_id(route: APIRoute) -> str:
    """The handler's own name, so ``list_roles`` becomes ``listRoles`` in the
    client rather than ``listRolesAdminRolesGet``. Handler names are therefore
    unique across the API; ``tests/test_openapi.py`` holds them to it."""
    return route.name


def render(app: FastAPI) -> str:
    return json.dumps(app.openapi(), indent=2, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if stale")
    parser.add_argument("--output", type=Path, default=SPEC_PATH)
    args = parser.parse_args(argv)

    # Imported here: ``remitx_api`` imports the app eagerly, and the app
    # imports this module for the tag names.
    from remitx_api.app import create_app
    from remitx_api.config import TestConfig

    spec = render(create_app(TestConfig))
    current = args.output.read_text() if args.output.exists() else ""

    if args.check:
        if current != spec:
            print(
                f"{args.output} is stale. "
                "Run: cd api && python scripts/export_openapi.py",
                file=sys.stderr,
            )
            return 1
        return 0

    if current != spec:
        args.output.write_text(spec)
        print(f"wrote {args.output}")
    return 0
