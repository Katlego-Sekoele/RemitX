"""The OpenAPI contract, and the export the frontend client is generated from.

The TypeScript client in ``frontend/app/client`` is generated by Hey API from
``frontend/openapi.json``, which is this module's output. Everything a client
author would otherwise have to guess — function names, grouping, which calls
need a session, what an error looks like — is declared here or on the routes::

    python scripts/export_openapi.py            # rewrite frontend/openapi.json
    python scripts/export_openapi.py --check    # exit 1 if it is stale

``tests/test_openapi.py`` runs the check, so CI and the pre-commit hook fail on
an API change whose spec was not regenerated.
"""

