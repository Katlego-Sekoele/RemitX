def _esc(value: object) -> str:
    return (
        str(value)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _user_categories(summary: RunSummary) -> list[int]:
    if summary.locust_steps:
        return list(summary.locust_steps)
    users: set[int] = set()
    for c in summary.compute:
        for p in c.plateaus:
            users.add(p.users)
    return sorted(users)


def _latency_series(summary: RunSummary, users: list[int]) -> list[dict]:
    tones = ("danger", "success", "info", "warning")
    series = []
    for i, c in enumerate(summary.compute):
        by_u = {p.users: p.http_median_ms for p in c.plateaus}
        series.append(
            {
                "name": f"{c.name} HTTP median (ms)",
                "data": [by_u.get(u) for u in users],
                "tone": tones[i % len(tones)],
            }
        )
    return series


def _rps_series(summary: RunSummary, users: list[int]) -> list[dict]:
    tones = ("danger", "success", "info", "warning")
    series = []
    for i, c in enumerate(summary.compute):
        by_u = {p.users: p.http_rps for p in c.plateaus}
        series.append(
            {
                "name": f"{c.name} HTTP req/s",
                "data": [by_u.get(u) for u in users],
                "tone": tones[i % len(tones)],
            }
        )
    return series


def _fmt_ms(value: float | None) -> str:
    if value is None:
        return "—"
    if value >= 1000:
        return f"{value / 1000:.1f} s"
    return f"{value:.0f} ms"


def _headline_stats(summary: RunSummary) -> dict:
    medians_at_10: list[tuple[str, float]] = []
    for c in summary.compute:
        p = next((x for x in c.plateaus if x.users == 10), None)
        if p and p.http_median_ms is not None:
            medians_at_10.append((c.name, p.http_median_ms))
    worst = max(medians_at_10, key=lambda t: t[1]) if medians_at_10 else None
    best = min(medians_at_10, key=lambda t: t[1]) if medians_at_10 else None
    peak_rps = max((c.peak_http_rps for c in summary.compute), default=0.0)
    peak_settle = max(
        (c.settle_throughput_at_peak_users for c in summary.compute), default=0.0
    )
    # Prefer highest-fail compute for the headline fail %
    http_fail = max((c.http_fail_pct for c in summary.compute), default=0.0)
    return {
        "worstHttpMedian": _fmt_ms(worst[1] if worst else None),
        "bestHttpMedian": _fmt_ms(best[1] if best else None),
        "peakHttpRps": f"{peak_rps:.1f}/s",
        "peakSettleRps": f"{peak_settle:.2f}/s",
        "httpFailPct": f"{http_fail:.1f}%",
        "httpFailTone": "danger" if http_fail >= 1 else "success",
    }


def _settle_table_rows(summary: RunSummary) -> list[list[str]]:
    rows = []
    for c in summary.compute:
        peak = c.plateaus[-1] if c.plateaus else None
        chain = peak.chain_confirm_median_ms if peak else None
        rows.append(
            [
                c.name,
                f"{c.settle_throughput_at_peak_users:.2f}",
                _fmt_ms(chain),
                f"{c.http_fail_pct:.1f}%",
                f"{c.settle_fail_pct:.1f}%",
            ]
        )
    return rows


def _endpoint_table_rows(summary: RunSummary) -> list[list[str]]:
    if not summary.compute:
        return []
    # Baseline = first compute step (low CPU first in sweep profiles).
    baseline = summary.compute[0]
    return [
        [
            e.name,
            f"{e.median_ms:.0f}",
            str(e.requests),
            str(e.failures),
        ]
        for e in baseline.endpoints_at_10
    ]


