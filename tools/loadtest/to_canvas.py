"""Turn a load-test results folder into summary + canvas + HTML report.

Writes summary.json, report.canvas.tsx, and performance-report.html.

python to_canvas.py tools/loadtest/results/<timestamp>
make loadtest-canvas RESULTS=tools/loadtest/results/<timestamp>
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from loadtest_summary import RunSummary, build_summary, summary_to_dict

HERE = Path(__file__).resolve().parent


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "run_dir",
        type=Path,
        help="Results folder (contains profile.json and compute/*/stats)",
    )
    args = parser.parse_args(argv)
    run_dir = args.run_dir.resolve()
    if not run_dir.is_dir():
        print(f"to_canvas: not a directory: {run_dir}", file=sys.stderr)
        return 1
    try:
        summary = build_summary(run_dir)
    except (FileNotFoundError, ValueError, json.JSONDecodeError, KeyError) as exc:
        print(f"to_canvas: {exc}", file=sys.stderr)
        return 1

    summary_path = run_dir / "summary.json"
    summary_path.write_text(json.dumps(summary_to_dict(summary), indent=2) + "\n")
    canvas_path = run_dir / "report.canvas.tsx"
    canvas_path.write_text(render_canvas(summary))
    html_path = run_dir / "performance-report.html"
    html_path.write_text(render_html(summary))
    print(f"Wrote {summary_path}")
    print(f"Wrote {canvas_path}")
    print(f"Wrote {html_path}")
    return 0


def _report_payload(summary: RunSummary) -> dict:
    user_cats = _user_categories(summary)
    return {
        "userCats": [str(u) for u in user_cats],
        "latencySeries": _latency_series(summary, user_cats),
        "rpsSeries": _rps_series(summary, user_cats),
        "headline": _headline_stats(summary),
        "settleRows": _settle_table_rows(summary),
        "endpointRows": _endpoint_table_rows(summary),
        "bottleneck": summary.bottleneck,
        "profileName": summary.profile_name,
        "description": summary.description,
        "burnP50": summary.burn_p50_s,
        "burnP95": summary.burn_p95_s,
        "computeLabels": ", ".join(
            f"{c.name} (API {c.api_cpus} / worker {c.worker_cpus} / "
            f"pg {c.postgres_cpus} CPU)"
            for c in summary.compute
        ),
        "locustSteps": summary.locust_steps,
    }


